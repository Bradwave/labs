#!/usr/bin/env node
// Labs · tools/readme.mjs
// Rewrites the gallery of labs in the root README.md (between <!-- labs:start --> and <!-- labs:end -->)
// from apps.json: screenshot, name, description in English and Italian, links. Run after adding a lab
// or changing a description.
// Usage: node tools/readme.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { KIT_ROOT, loadApps } from "./lib.mjs";

const SITE = "https://labs.matephis.com";
const apps = loadApps();
const cell = (a) => {
  const shot = existsSync(join(KIT_ROOT, a.slug, "docs", "screenshot.png")) ? `<a href="${a.slug}/"><img src="${a.slug}/docs/screenshot.png" alt="${a.name}" width="400"></a><br>` : "";
  const tags = [a.subject, a.kind === "xr" ? "XR" : null, a.kit === true ? null : "<i>being updated</i>"].filter(Boolean).join(" · ");
  return `${shot}<b><a href="${SITE}/${a.slug}/">${a.name}</a></b> · <a href="${a.slug}/">code</a><br>${a.description.en}<br><i>${a.description.it}</i><br><sub>${tags}</sub>`;
};
const rows = [];
for (let i = 0; i < apps.length; i += 2) rows.push(`<tr>\n<td width="50%" valign="top">${cell(apps[i])}</td>\n<td width="50%" valign="top">${apps[i + 1] ? cell(apps[i + 1]) : ""}</td>\n</tr>`);
const gallery = `<!-- labs:start (generated by tools/readme.mjs from apps.json: do not edit by hand) -->\n<table>\n${rows.join("\n")}\n</table>\n<!-- labs:end -->`;

const path = join(KIT_ROOT, "README.md");
const s = readFileSync(path, "utf8");
const out = s.replace(/<!-- labs:start[\s\S]*?<!-- labs:end -->/, gallery);
if (out === s && !s.includes("<!-- labs:start")) throw new Error("README.md has no <!-- labs:start --> … <!-- labs:end --> markers");
writeFileSync(path, out);
console.log(`README.md: ${apps.length} labs`);
