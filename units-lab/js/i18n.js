let LANG = (() => {
  try {
    const s = localStorage.getItem("units-lab.lang");
    if (s === "it" || s === "en") return s;
  } catch (e) {
    /* storage may be blocked */
  }
  const nav = typeof navigator !== "undefined" ? navigator.language || "it" : "it";
  return nav.toLowerCase().startsWith("en") ? "en" : "it";
})();

const getLang = () => LANG;

function setLang(l) {
  LANG = l;
  try {
    localStorage.setItem("units-lab.lang", l);
  } catch (e) {
    /* */
  }
  if (typeof document !== "undefined") document.documentElement.lang = l;
}

function t(key, ...args) {
  let s = DICT[LANG][key];
  if (s == null) s = DICT.en[key];
  if (s == null) s = key;
  return s.replace(/\{(\d)\}/g, (m, i) => (args[+i] !== undefined ? args[+i] : m));
}

function applyI18n(root) {
  document.documentElement.lang = LANG;
  root.querySelectorAll("[data-i18n]").forEach((e) => {
    e.innerHTML = t(e.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-title]").forEach((e) => {
    const s = t(e.dataset.i18nTitle).replace(/<[^>]+>/g, "");
    e.title = s;
    e.setAttribute("aria-label", s);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach((e) => {
    e.setAttribute("aria-label", t(e.dataset.i18nAria).replace(/<[^>]+>/g, ""));
  });
}

export { DICT, t, getLang, setLang, applyI18n };
